    static String t(String raw){
        if(raw==null)return "";
        String exact=TEXT.get(raw);
        if(exact!=null)return exact;
        if(raw.startsWith("●  "))return "●  "+t(raw.substring(3));
        if(raw.startsWith("Reset ")&&raw.endsWith("?"))return "¿Restablecer "+t(raw.substring(6,raw.length()-1))+"?";
        if(raw.endsWith(" · restart"))return t(raw.substring(0,raw.length()-10))+" · reiniciar";
        if(raw.endsWith(" · unsupported"))return t(raw.substring(0,raw.length()-14))+" · no compatible";
        if(raw.startsWith("Every ")&&raw.endsWith(" frames"))return "Cada "+raw.substring(6,raw.length()-7)+" fotogramas";
        if(raw.endsWith(" seconds"))return raw.substring(0,raw.length()-8)+" segundos";
        if(raw.endsWith(" workers"))return raw.substring(0,raw.length()-8)+" procesos";
        if(raw.endsWith(" worker"))return raw.substring(0,raw.length()-7)+" proceso";
        if(raw.endsWith(" unlocked"))return raw.substring(0,raw.length()-9)+" desbloqueados";
        if(raw.startsWith("Latest report: "))return "Último informe: "+raw.substring(15);
        if(raw.startsWith("Last launch failed: "))return "Falló el último inicio: "+raw.substring(20);
        if(raw.startsWith("Could not delete report: "))return "No se pudo eliminar el informe: "+raw.substring(25);
        if(raw.startsWith("Could not save the driver choice: "))return "No se pudo guardar el controlador: "+raw.substring(34);
        if(raw.startsWith("Delete "))return "Eliminar "+raw.substring(7);
        return raw;
    }
    static String guide(String key){
        String value=GUIDES.get(key);
        return value!=null?value:"Este ajuste modifica el comportamiento de la aplicación o del juego. Guarda los cambios y reinicia si se indica.";
    }
